import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { once } from 'node:events';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { setTimeout as delay } from 'node:timers/promises';
import { Store } from '../service/store.mjs';
import { Runtime } from '../service/runtime.mjs';
import { createControlServer } from '../service/control.mjs';

const directory = await mkdtemp(join(tmpdir(), 'tac-range-ui-')), store = new Store(join(directory, 'collector.sqlite'));
const today = globalThis.AnchorCore.shanghaiToday();
const offset = n => new Date(Date.parse(`${today}T00:00:00Z`) + n * 86400000).toISOString().slice(0, 10);
const profile = { anchorId: '7601032374063105082', douyinId: 'range-ui-only', nickname: '测试（三角洲行动）', followers: 100 };
const collected = [], source = { async open() {}, async close() {}, async collect(kind, date, receive) {
  await delay(30);
  if (kind === 'daily') collected.push(date);
  receive([kind === 'profiles' ? profile : { ...profile, date, waves: Number(date.slice(-2)), liveSeconds: 3600, acu: Number(date.slice(-2)) + 0.5 }], { scanned: 1, total: 1, identified: 1 });
} };
const runtime = new Runtime({ store, source, config: { intervalSeconds: 600, lookbackDays: 2, includeToday: true }, dataDir: directory });
const server = createControlServer(runtime, { port: 0 }); server.listen(0, '127.0.0.1'); await once(server, 'listening');
let browser;
try {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1320, height: 1100 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:' + server.address().port;
  await page.goto(base);
  await page.getByText('自动日期（每天滚动）', { exact: false }).waitFor();
  await page.getByRole('button', { name: '昨日', exact: true }).click();
  assert.equal(await page.getByLabel('开始日期').inputValue(), offset(-1));
  await page.getByRole('button', { name: '按所选日期采集', exact: true }).click();
  await page.getByText('当前区间已保存 1 条记录，覆盖 1/1 天', { exact: true }).waitFor();
  assert.deepEqual(collected, [offset(-1)]);
  assert.equal(store.records()[0].acu, Number(offset(-1).slice(-2)) + 0.5);
  await page.getByLabel('开始日期').fill(offset(-2));
  await page.getByLabel('结束日期').fill(offset(-1));
  await page.getByRole('button', { name: '按所选日期采集', exact: true }).click();
  await page.getByText('当前区间已保存 2 条记录，覆盖 2/2 天', { exact: true }).waitFor();
  assert.deepEqual(collected, [offset(-1), offset(-2), offset(-1)]);
  assert.match(await page.locator('#collection-quality').textContent(), /ACU 缺失 0 条，音浪缺失 0 条，直播时长缺失 0 条/);
  const exported = await (await fetch(base + await page.locator('#range-json').getAttribute('href'))).json();
  assert.deepEqual(exported.readyRecords.map(row => row.date), [offset(-2), offset(-1)]);
  await page.reload();
  await page.getByText('指定日期（已保存）', { exact: false }).waitFor();
  assert.equal(await page.getByLabel('开始日期').inputValue(), offset(-2));
  assert.equal(await page.getByLabel('结束日期').inputValue(), offset(-1));
  await page.getByLabel('开始日期').fill(today);
  await page.getByRole('button', { name: '按所选日期采集', exact: true }).click();
  await page.getByText('开始日期不能晚于结束日期', { exact: true }).waitFor();
  assert.equal(store.collectionSelection().start, offset(-2));
  await page.reload();
  await page.getByText('指定日期（已保存）', { exact: false }).waitFor();
  await mkdir(new URL('../artifacts/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../artifacts/date-range-ui-offline-test.png', import.meta.url)), fullPage: true });
  await page.getByRole('button', { name: '今日', exact: true }).click();
  await page.getByRole('button', { name: '按所选日期采集', exact: true }).click();
  await page.getByText('当前区间已保存 1 条记录，覆盖 1/1 天', { exact: true }).waitFor();
  assert.equal(store.records({ start: today, end: today })[0].snapshotReady, true);
  await page.getByRole('button', { name: '恢复自动日期', exact: true }).click();
  await page.getByText('自动日期（每天滚动）', { exact: false }).waitFor();
  await page.getByText('当前区间已保存 3 条记录，覆盖 3/3 天', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('PASS real Edge offline: single day → inclusive multi-day range → exact date-specific ACU/export → reload persistence → invalid range rejected → today provisional → restore rolling dates; mobile layout and zero page errors. No platform or production ERP requests.');
} finally {
  await browser?.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await runtime.close(); store.close();
  await rm(directory, { recursive: true, force: true, maxRetries: 10, retryDelay: 50 });
}
